#!/usr/bin/env node
/**
 * Scans public/ for GLB/HDR files and generates a deterministic asset manifest.
 * Run before dev/build — no runtime HEAD requests needed.
 */
import { existsSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const publicDir = join(root, "public");

/** Registry asset id → public-relative path */
const ASSET_PATHS = {
  "athlete-hero": "models/characters/athlete.glb",
  barbell: "models/equipment/barbell.glb",
  dumbbell: "models/equipment/dumbbell.glb",
  kettlebell: "models/equipment/kettlebell.glb",
  bench: "models/equipment/bench.glb",
  plates: "models/equipment/plates.glb",
  "squat-rack": "models/equipment/squat-rack.glb",
  "cable-machine": "models/equipment/cable-machine.glb",
  rower: "models/equipment/rower.glb",
  treadmill: "models/equipment/treadmill.glb",
  bike: "models/equipment/bike.glb",
  sled: "models/equipment/sled.glb",
  "boxing-bag": "models/equipment/boxing-bag.glb",
  "gym-floor": "models/environment/gym-floor.glb",
  "gym-walls": "models/environment/gym-walls.glb",
  "gym-ceiling": "models/environment/gym-ceiling.glb",
  "gym-pillars": "models/environment/gym-pillars.glb",
  "gym-mirrors": "models/environment/gym-mirrors.glb",
  "gym-doors": "models/environment/gym-doors.glb",
  "gym-windows": "models/environment/gym-windows.glb",
  "gym-lighting-fixtures": "models/environment/gym-lighting-fixtures.glb",
  "hdr-studio": "hdr/studio/studio.hdr",
  "hdr-gym-dark": "hdr/dark/gym-dark.hdr",
  "hdr-gym-dramatic": "hdr/gym/gym-dramatic.hdr",
  "hdr-neutral": "hdr/studio/neutral.hdr",
};

function fileExists(relativePath) {
  return existsSync(join(publicDir, relativePath));
}

const assets = {};
const byCategory = {
  characters: {},
  equipment: {},
  environment: {},
  hdr: {},
};

for (const [id, relPath] of Object.entries(ASSET_PATHS)) {
  const available = fileExists(relPath);
  assets[id] = available;

  if (id.startsWith("hdr-")) {
    byCategory.hdr[id] = available;
  } else if (id === "athlete-hero") {
    byCategory.characters[id] = available;
  } else if (id.startsWith("gym-")) {
    byCategory.environment[id] = available;
  } else {
    byCategory.equipment[id] = available;
  }
}

const manifest = {
  generatedAt: new Date().toISOString(),
  assets,
  characters: byCategory.characters,
  equipment: byCategory.equipment,
  environment: byCategory.environment,
  hdr: byCategory.hdr,
};

const manifestJsonPath = join(publicDir, "asset-manifest.json");
writeFileSync(manifestJsonPath, JSON.stringify(manifest, null, 2) + "\n");

const tsPath = join(root, "src/lib/three/assets/manifest.generated.ts");
mkdirSync(dirname(tsPath), { recursive: true });
writeFileSync(
  tsPath,
  `/** AUTO-GENERATED by scripts/generate-asset-manifest.mjs — do not edit */\n\nexport const ASSET_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n\nexport type AssetManifestId = keyof typeof ASSET_MANIFEST.assets;\n`,
);

const availableCount = Object.values(assets).filter(Boolean).length;
console.log(
  `[forge] asset manifest: ${availableCount}/${Object.keys(assets).length} assets available`,
);
console.log(`[forge] wrote ${manifestJsonPath}`);
console.log(`[forge] wrote ${tsPath}`);
